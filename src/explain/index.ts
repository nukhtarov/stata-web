// Пояснения простыми словами к каждому выводу.
import { fmtG, humanNumber, pEq } from '../stats/format';
import type { AssumptionUpdate, Explanation, ResultData } from '../lang/types';

export const MAIN_RULE =
  'Главное правило: p < 0,05 → гипотезу H0 отвергаем. Для модели и факторов хорошо маленькое p (значимы), для проверок предпосылок — большое (предпосылка выполнена).';

const pct = (x: number) => (x * 100).toFixed(1).replace('.', ',') + '%';
const num = (x: number, d = 2) => x.toFixed(d).replace('.', ',');
const pw = (p: number) => `p ${pEq(p)}`;

interface Ctx {
  residVars: Set<string>;
}

export function explain(d: ResultData, _s?: Ctx): Explanation | undefined {
  switch (d.kind) {
    case 'regress':
      return regress(d.m);
    case 'linktest': {
      const hs = d.m.coefs.find((c) => c.name === '_hatsq')!;
      const ok = hs.p >= 0.05;
      return {
        verdict: ok ? 'good' : 'bad',
        title: ok ? 'Форма модели подобрана верно' : 'Форма модели подобрана неверно',
        text: [
          'linktest проверяет первую предпосылку (П1): правильно ли выбрана форма модели. Он строит вспомогательную регрессию цены на прогноз (_hat) и квадрат прогноза (_hatsq).',
          'Шапку таблицы (R², F, Prob > F) здесь не смотрим — это вспомогательная регрессия, а не ваша модель. Смотрим только строку _hatsq.',
          ok
            ? `У _hatsq ${pw(hs.p)} ≥ 0,05 — квадрат прогноза ничего не добавляет, значит форма модели (линейная) подходит.`
            : `У _hatsq ${pw(hs.p)} < 0,05 — квадрат прогноза значим, значит модели не хватает нелинейности или пропущены важные переменные. Попробуйте логарифмы (gen lnX = ln(X)) или квадраты факторов.`,
          MAIN_RULE,
        ],
        report: ok
          ? `Тест linktest: P>|t| для _hatsq = ${num(hs.p, 3)} > 0,05, гипотеза о правильной спецификации модели не отвергается — предпосылка П1 выполняется.`
          : `Тест linktest: P>|t| для _hatsq = ${num(hs.p, 3)} < 0,05, гипотеза о правильной спецификации модели отвергается — предпосылка П1 нарушена (ошибка спецификации).`,
        assumptions: [{ id: 'P1', status: ok ? 'ok' : 'bad', source: 'linktest', note: `_hatsq ${pw(hs.p)}` }],
      };
    }
    case 'ovtest': {
      const ok = d.p >= 0.05;
      return {
        verdict: ok ? 'good' : 'bad',
        title: ok ? 'Пропущенных переменных не обнаружено' : 'В модели пропущены переменные или нелинейность',
        text: [
          'Тест Рамсея (RESET) тоже проверяет П1: добавляет в модель степени прогноза и смотрит, стала ли модель лучше. H0: пропущенных переменных нет.',
          ok
            ? `Prob > F ${pEq(d.p)}, это не меньше 0,05 — добавки не помогают, значит важных переменных и нелинейности не упущено.`
            : `Prob > F ${pEq(d.p)}, это меньше 0,05 — добавки улучшают модель, значит в модели не хватает важных факторов или нужна нелинейная форма (логарифмы, квадраты).`,
          MAIN_RULE,
        ],
        report: ok
          ? `Тест Рамсея: F(${d.df1}, ${d.df2}) = ${num(d.F)}, Prob > F = ${num(d.p, 4)} > 0,05 — гипотеза об отсутствии пропущенных переменных не отвергается, предпосылка П1 выполняется.`
          : `Тест Рамсея: F(${d.df1}, ${d.df2}) = ${num(d.F)}, Prob > F = ${num(d.p, 4)} < 0,05 — гипотеза об отсутствии пропущенных переменных отвергается, предпосылка П1 нарушена.`,
        assumptions: [{ id: 'P1', status: ok ? 'ok' : 'bad', source: 'ovtest', note: `RESET ${pw(d.p)}` }],
      };
    }
    case 'vif': {
      const bad = d.rows.filter((r) => r.vif > 10);
      const ok = bad.length === 0;
      const list = bad.map((r) => `${r.name} (VIF = ${num(r.vif)}, ошибка завышена в ${num(Math.sqrt(r.vif), 1)} раза)`);
      return {
        verdict: ok ? 'good' : 'bad',
        title: ok ? 'Сильной мультиколлинеарности нет' : 'Есть сильная мультиколлинеарность',
        text: [
          'VIF проверяет П2 — нет ли сильной взаимосвязи между факторами (мультиколлинеарности). Когда факторы похожи друг на друга, модель не может разделить их влияние, и стандартные ошибки раздуваются: √VIF показывает, во сколько раз.',
          'Правило: VIF > 10 — сильная мультиколлинеарность.',
          ok
            ? `Все VIF меньше 10 (максимум — ${d.rows[0].name}, ${num(d.rows[0].vif)}). Средний VIF = ${num(d.mean)}.`
            : `VIF > 10 у ${bad.length === 1 ? 'фактора' : 'факторов'}: ${list.join('; ')}. Из-за этого они могут оказаться «незначимыми», хотя на самом деле влияют. Решение — убрать один из похожих факторов или объединить их.`,
        ],
        report: ok
          ? `Все значения VIF меньше 10 (средний VIF = ${num(d.mean)}), сильной мультиколлинеарности нет — предпосылка П2 выполняется.`
          : `Значения VIF превышают 10 для переменных ${bad.map((r) => `${r.name} (${num(r.vif)})`).join(', ')}; средний VIF = ${num(d.mean)}. В модели присутствует сильная мультиколлинеарность — предпосылка П2 нарушена.`,
        assumptions: [{ id: 'P2', status: ok ? 'ok' : 'bad', source: 'vif', note: ok ? `max VIF ${num(d.rows[0].vif)}` : `VIF>10: ${bad.map((r) => r.name).join(', ')}` }],
      };
    }
    case 'swilk': {
      const r = d.rows[0];
      const ok = r.p >= 0.05;
      return {
        verdict: ok ? 'good' : 'bad',
        title: ok ? 'Распределение не отличается от нормального' : 'Распределение отличается от нормального',
        text: [
          `Тест Шапиро–Уилка проверяет${d.isResid ? ' П5 —' : ''} нормально ли распределены ${d.isResid ? 'остатки' : `значения ${r.name}`} (похоже ли распределение на симметричный «колокол»). H0: распределение нормальное.`,
          ok
            ? `Prob>z ${pEq(r.p)}, это не меньше 0,05 — отличий от нормального распределения нет. W = ${num(r.W, 3)} (чем ближе к 1, тем лучше).`
            : `Prob>z ${pEq(r.p)}, это меньше 0,05 — распределение заметно отличается от нормального. Возможные причины: выбросы, асимметрия. Посмотрите kdensity и попробуйте логарифм зависимой переменной.`,
          MAIN_RULE,
        ],
        report: ok
          ? `Тест Шапиро–Уилка: W = ${num(r.W, 5)}, Prob>z = ${num(r.p, 4)} > 0,05 — гипотеза о нормальном распределении ${d.isResid ? 'остатков ' : ''}не отвергается${d.isResid ? ', предпосылка П5 выполняется' : ''}.`
          : `Тест Шапиро–Уилка: W = ${num(r.W, 5)}, Prob>z = ${num(r.p, 4)} < 0,05 — гипотеза о нормальном распределении ${d.isResid ? 'остатков ' : ''}отвергается${d.isResid ? ', предпосылка П5 нарушена' : ''}.`,
        assumptions: d.isResid ? [{ id: 'P5', status: ok ? 'ok' : 'bad', source: 'swilk', note: `Shapiro–Wilk ${pw(r.p)}` }] : undefined,
      };
    }
    case 'sktest': {
      const r = d.rows[0];
      const ok = r.p >= 0.05;
      const parts: string[] = [];
      if (r.pSkew < 0.05) parts.push('асимметрия (распределение перекошено в одну сторону)');
      if (r.pKurt < 0.05) parts.push('эксцесс (слишком острая вершина или «тяжёлые хвосты» — выбросы)');
      const who = d.isResid ? 'остатков ' : '';
      return {
        verdict: ok ? 'good' : 'bad',
        title: ok ? 'Распределение не отличается от нормального' : 'Распределение отличается от нормального',
        text: [
          `sktest проверяет${d.isResid ? ' П5 —' : ''} нормальность ${d.isResid ? 'остатков' : `значений ${r.name}`} по двум признакам: асимметрии (Pr(Skewness)) и эксцессу (Pr(Kurtosis)). Главный — совместный тест Prob>chi2. H0: распределение нормальное.`,
          ok
            ? `Prob>chi2 ${pEq(r.p)}, это не меньше 0,05 — отличий от нормального распределения нет.`
            : `Prob>chi2 ${pEq(r.p)}, это меньше 0,05 — распределение отличается от нормального.${parts.length ? ` Проблема — ${parts.join(' и ')}.` : ''} Посмотрите qnorm и kdensity, проверьте выбросы, попробуйте логарифм зависимой переменной.`,
          `По отдельности: асимметрия p ${pEq(r.pSkew)}, эксцесс p ${pEq(r.pKurt)}.`,
          MAIN_RULE,
        ],
        report: ok
          ? `Тест на асимметрию и эксцесс (sktest): adj chi2(2) = ${Number.isNaN(r.chi2) ? '—' : num(r.chi2)}, Prob>chi2 = ${num(r.p, 4)} > 0,05 — гипотеза о нормальном распределении ${who}не отвергается${d.isResid ? ', предпосылка П5 выполняется' : ''}.`
          : `Тест на асимметрию и эксцесс (sktest): adj chi2(2) = ${Number.isNaN(r.chi2) ? 'очень велик' : num(r.chi2)}, Prob>chi2 = ${num(r.p, 4)} < 0,05 — гипотеза о нормальном распределении ${who}отвергается${d.isResid ? ', предпосылка П5 нарушена' : ''}.`,
        assumptions: d.isResid ? [{ id: 'P5', status: ok ? 'ok' : 'bad', source: 'sktest', note: `Skewness/Kurtosis ${pw(r.p)}` }] : undefined,
      };
    }
    case 'hettest': {
      const ok = d.p >= 0.05;
      return {
        verdict: ok ? 'good' : 'bad',
        title: ok ? 'Гетероскедастичности нет' : 'Есть гетероскедастичность',
        text: [
          'Тест Бройша–Пагана проверяет П4 — одинаков ли разброс ошибок модели для всех наблюдений (гомоскедастичность). H0: разброс постоянный.',
          ok
            ? `Prob > chi2 ${pEq(d.p)}, это не меньше 0,05 — разброс ошибок одинаковый, стандартные ошибки и p-значения в регрессии можно использовать.`
            : `Prob > chi2 ${pEq(d.p)}, это меньше 0,05 — разброс ошибок меняется (обычно растёт с прогнозом). Коэффициенты остаются несмещёнными, но стандартные ошибки неверны — используйте робастные ошибки: reg …, vce(robust).`,
          MAIN_RULE,
        ],
        report: ok
          ? `Тест Бройша–Пагана: chi2(${d.df}) = ${num(d.chi2)}, Prob > chi2 = ${num(d.p, 4)} > 0,05 — гипотеза о гомоскедастичности не отвергается, предпосылка П4 выполняется.`
          : `Тест Бройша–Пагана: chi2(${d.df}) = ${num(d.chi2)}, Prob > chi2 = ${num(d.p, 4)} < 0,05 — гипотеза о гомоскедастичности отвергается, в модели присутствует гетероскедастичность (предпосылка П4 нарушена).`,
        assumptions: [{ id: 'P4', status: ok ? 'ok' : 'bad', source: 'hettest', note: `Breusch–Pagan ${pw(d.p)}` }],
      };
    }
    case 'imtest':
      return imtest(d);
    case 'summarize':
      return summarize(d);
    case 'correlate':
      return correlate(d);
    case 'graph':
      return graph(d);
    case 'import': {
      const t = [`Загружено ${d.nvars} переменных и ${d.nobs} наблюдений. Проверьте типы командой describe.`];
      if (d.commaNumeric.length)
        t.push(
          `Похоже, ${d.commaNumeric.join(', ')} — числа с запятой: Stata прочитала их как текст. Переведите в числа: destring ${d.commaNumeric.join(' ')}, replace dpcomma`,
        );
      return { verdict: d.commaNumeric.length ? 'bad' : 'info', title: 'Данные загружены', text: t };
    }
    case 'describe':
      return {
        verdict: 'info',
        title: `${d.N} наблюдений, ${d.k} переменных`,
        text: [
          'storage type — тип хранения: byte, int, long, float, double — числа; str# — текст (# — максимальная длина). В регрессию можно включать только числовые переменные.',
          'Если нужная переменная оказалась str, её надо перевести в числа: destring имя, replace (а если числа с запятой — destring имя, replace dpcomma).',
        ],
      };
    case 'predict':
      return d.what === 'resid'
        ? {
            verdict: 'info',
            title: `Создана переменная ${d.name} — остатки модели`,
            text: [`Остатки e = y − ŷ — ошибки модели для каждого наблюдения. Дальше по ним проверяют предпосылки: sum ${d.name} (среднее ≈ 0, П3), kdensity ${d.name}, normal и swilk ${d.name} (нормальность, П5).`],
          }
        : { verdict: 'info', title: `Создана переменная ${d.name} — прогноз модели`, text: ['ŷ — значение зависимой переменной, которое предсказывает модель для каждого наблюдения.'] };
    default:
      return undefined;
  }
}

function regress(m: import('../stats/ols').OLSResult): Explanation {
  const ok = m.pF < 0.05;
  const live = m.coefs.filter((c) => !c.omitted && c.name !== '_cons');
  const sig = live.filter((c) => c.p < 0.05);
  const insig = live.filter((c) => c.p >= 0.05);
  const text: string[] = [];
  text.push(
    ok
      ? `Модель в целом значима: Prob > F ${pEq(m.pF)}, это меньше 0,05. Значит, хотя бы один фактор действительно влияет на ${m.depvar}.`
      : `Модель в целом незначима: Prob > F ${pEq(m.pF)}, это не меньше 0,05. Факторы вместе не объясняют ${m.depvar} лучше, чем простое среднее.`,
  );
  text.push(`R² = ${num(m.r2, 4)}: модель объясняет ${pct(m.r2)} различий в ${m.depvar} между наблюдениями.`);
  if (m.r2 - m.adjr2 > 0.05)
    text.push(`Скорректированный R² (${num(m.adjr2, 4)}) заметно ниже обычного — в модели есть лишние факторы, которые почти ничего не добавляют.`);
  if (sig.length) {
    text.push('Значимые факторы (P>|t| < 0,05):');
    for (const c of sig)
      text.push(
        `• ${c.name}: при росте ${c.name} на 1 ${m.depvar} ${c.b > 0 ? 'растёт' : 'падает'} в среднем на ${humanNumber(Math.abs(c.b), 4)} при прочих равных (P>|t| ${pEq(c.p, 3)}).`,
      );
  } else text.push('Ни один фактор не значим по отдельности (у всех P>|t| ≥ 0,05).');
  if (insig.length) text.push(`Незначимы (P>|t| ≥ 0,05): ${insig.map((c) => c.name).join(', ')} — их влияние статистически не подтверждено.`);
  if (m.omitted.length) text.push(`Исключены из-за коллинеарности (точная линейная зависимость от других факторов): ${m.omitted.join(', ')}.`);
  if (m.vce === 'robust')
    text.unshift(
      'Это регрессия с робастными (устойчивыми, Huber–White) стандартными ошибками. Коэффициенты и R² те же, что в обычной регрессии; меняются Std. Err., t, P>|t|, доверительные интервалы и F-тест — они остаются верными и при гетероскедастичности (нарушении П4). Выводы о значимости делайте по этой таблице.',
    );
  text.push('_cons (константа) — значение при всех факторах, равных нулю; её обычно не интерпретируют.');
  text.push(MAIN_RULE);
  const report =
    (m.vce === 'robust' ? 'С учётом робастных стандартных ошибок: ' : '') +
    `Построена регрессия ${m.depvar} на ${live.length} ${live.length === 1 ? 'фактор' : live.length < 5 ? 'фактора' : 'факторов'} (N = ${m.N}). ` +
    (ok
      ? `Модель значима в целом: F(${m.dfm}, ${m.dfr}) = ${num(m.F)}, Prob > F = ${num(m.pF, 4)} < 0,05. `
      : `Модель незначима: F(${m.dfm}, ${m.dfr}) = ${num(m.F)}, Prob > F = ${num(m.pF, 4)} > 0,05. `) +
    `Коэффициент детерминации R² = ${num(m.r2, 4)}, то есть модель объясняет ${pct(m.r2)} вариации ${m.depvar} (скорректированный R² = ${num(m.adjr2, 4)}). ` +
    (sig.length
      ? `На уровне 5% значимы: ${sig.map((c) => `${c.name} (коэффициент ${humanNumber(c.b, 4)}, p ${pEq(c.p, 3)})`).join(', ')}.`
      : 'Ни один из факторов не значим на уровне 5%.');
  return { verdict: ok ? 'good' : 'bad', title: ok ? 'Модель значима' : 'Модель незначима', text, report };
}

function imtest(d: Extract<ResultData, { kind: 'imtest' }>): Explanation {
  const all = [d.het, d.skew, d.kurt];
  const ok = all.every((r) => r.p >= 0.05);
  const assumptions: AssumptionUpdate[] = [
    { id: 'P4', status: d.saturated ? 'warn' : d.het.p >= 0.05 ? 'ok' : 'bad', source: 'imtest', note: `Heteroskedasticity ${pw(d.het.p)}${d.saturated ? ' (тест перегружен)' : ''}` },
    { id: 'P5', status: d.skew.p >= 0.05 && d.kurt.p >= 0.05 ? 'ok' : 'bad', source: 'imtest', note: `Skewness ${pw(d.skew.p)}, Kurtosis ${pw(d.kurt.p)}` },
  ];
  const line = (name: string, what: string, r: { p: number }) =>
    `• ${name} (${what}): p ${pEq(r.p)} — ${r.p >= 0.05 ? 'хорошо, нарушения нет' : 'плохо, есть нарушение'}.`;
  return {
    verdict: ok ? 'good' : 'bad',
    title: ok ? 'Нарушений не обнаружено' : 'Обнаружены нарушения предпосылок',
    text: [
      'IM-тест (Камерон и Триведи) проверяет сразу три вещи. В каждой строке H0 — «всё в порядке», значит хорошо большое p.',
      line('Heteroskedasticity', 'одинаков ли разброс ошибок, П4', d.het),
      line('Skewness', 'симметричны ли остатки, П5', d.skew),
      line('Kurtosis', 'нет ли «тяжёлых хвостов» у остатков, П5', d.kurt),
      MAIN_RULE,
    ],
    warning: d.saturated
      ? `Тест перегружен: во вспомогательной регрессии ${d.het.df} переменных при ${d.N} наблюдениях — слишком много переменных для такого числа наблюдений, R² = 1 автоматически. Строке Heteroskedasticity не доверяйте — опирайтесь на estat hettest.`
      : undefined,
    report:
      `По результатам IM-теста: гетероскедастичность — chi2(${d.het.df}) = ${num(d.het.chi2)}, p = ${num(d.het.p, 4)}; асимметрия — chi2(${d.skew.df}) = ${num(d.skew.chi2)}, p = ${num(d.skew.p, 4)}; эксцесс — chi2(${d.kurt.df}) = ${num(d.kurt.chi2)}, p = ${num(d.kurt.p, 4)}. ` +
      (ok ? 'Все p-значения больше 0,05, нарушений предпосылок П4 и П5 не выявлено.' : 'Есть p-значения меньше 0,05 — соответствующие предпосылки нарушены.') +
      (d.saturated ? ' Тест на гетероскедастичность в составе IM-теста неинформативен из-за малого числа наблюдений, вывод о П4 делается по тесту Бройша–Пагана.' : ''),
    assumptions,
  };
}

function summarize(d: Extract<ResultData, { kind: 'summarize' }>): Explanation {
  if (d.residVar) {
    const r = d.rows[0];
    const zero = Math.abs(r.mean) < 1e-6 * Math.max(1, d.residMaxAbs ?? 1);
    const sci = fmtG(r.mean).includes('e') ? ` В выводе может стоять запись вида 3.58e-06 — это 3,58 · 10⁻⁶ = 0,00000358, то есть практически ноль.` : '';
    return {
      verdict: zero ? 'good' : 'bad',
      title: zero ? 'Среднее остатков равно нулю (П3)' : 'Среднее остатков не равно нулю',
      text: [
        `Это остатки последней модели. П3 требует, чтобы в среднем ошибки модели были равны нулю. Mean = ${humanNumber(r.mean, 3)}.${sci}`,
        zero
          ? 'Среднее практически равно нулю — предпосылка выполнена (в МНК с константой это всегда так).'
          : 'Среднее заметно отличается от нуля — проверьте, есть ли в модели константа и те ли это остатки.',
      ],
      report: zero
        ? `Среднее значение остатков равно ${humanNumber(r.mean, 3)} ≈ 0 — предпосылка П3 о нулевом математическом ожидании ошибок выполняется.`
        : `Среднее значение остатков равно ${humanNumber(r.mean, 3)} и отличается от нуля — предпосылка П3 нарушена.`,
      assumptions: [{ id: 'P3', status: zero ? 'ok' : 'bad', source: 'sum', note: `mean = ${humanNumber(r.mean, 3)}` }],
    };
  }
  const miss = d.rows.filter((r) => r.N === 0).map((r) => r.name);
  const Ns = new Set(d.rows.filter((r) => r.N > 0).map((r) => r.N));
  const text = [
    'Obs — число заполненных наблюдений, Mean — среднее, Std. Dev. — стандартное отклонение (типичный разброс вокруг среднего), Min и Max — наименьшее и наибольшее значения.',
  ];
  if (miss.length) text.push(`Obs = 0 у ${miss.join(', ')} — это текстовые переменные (или пустые), для них статистики не считаются.`);
  if (Ns.size > 1) text.push('У переменных разное число наблюдений — где-то есть пропуски. В регрессию попадут только строки, заполненные во всех переменных модели.');
  return { verdict: 'info', title: 'Описательная статистика', text };
}

function cheddock(r: number): string {
  const a = Math.abs(r);
  if (a < 0.3) return 'практически нет';
  if (a < 0.5) return 'слабая';
  if (a < 0.7) return 'умеренная';
  if (a < 0.9) return 'сильная';
  return 'очень сильная';
}

function correlate(d: Extract<ResultData, { kind: 'correlate' }>): Explanation {
  const dep = d.names[0];
  const text = [
    'Коэффициент корреляции показывает силу линейной связи (от −1 до 1): знак — направление (плюс — вместе растут, минус — одна растёт, другая падает), модуль — сила по шкале Чеддока: < 0,3 — связи нет, 0,3–0,5 — слабая, 0,5–0,7 — умеренная (средняя), 0,7–0,9 — сильная, > 0,9 — очень сильная.',
  ];
  if (d.names.length > 1) {
    const withDep = d.names.slice(1).map((n, i) => ({ n, r: d.R[i + 1][0] })).sort((a, b) => Math.abs(b.r) - Math.abs(a.r));
    const top = withDep.slice(0, 3);
    text.push(`Сильнее всего с ${dep} связаны: ${top.map((t) => `${t.n} (${num(t.r)}, ${cheddock(t.r)}, ${t.r > 0 ? 'прямая' : 'обратная'})`).join('; ')}.`);
    const pairs: string[] = [];
    for (let i = 1; i < d.names.length; i++) for (let j = 1; j < i; j++) if (Math.abs(d.R[i][j]) >= 0.7) pairs.push(`${d.names[j]}–${d.names[i]} (${num(d.R[i][j])})`);
    if (pairs.length) text.push(`Сильно связаны между собой факторы: ${pairs.slice(0, 6).join(', ')}${pairs.length > 6 ? ' и др.' : ''}. Это сигнал возможной мультиколлинеарности — проверьте vif после регрессии.`);
    if (d.P) {
      const lvl = d.star ?? 0.05;
      const lv = num(lvl, String(lvl).split('.')[1]?.length ?? 2);
      const sig = d.names.slice(1).filter((_, i) => d.P![i + 1][0] <= lvl);
      const ns = d.names.slice(1).filter((_, i) => !(d.P![i + 1][0] <= lvl));
      text.push(
        `Значимость (H0: корреляция равна нулю)${d.star !== undefined ? ' — звёздочка стоит там, где p ≤ ' + lv : ''}. ` +
          (sig.length ? `С ${dep} значимо связаны: ${sig.join(', ')}. ` : `Ни один фактор не связан с ${dep} значимо. `) +
          (ns.length ? `Связь не подтверждается (p > ${lv}): ${ns.join(', ')}.` : ''),
      );
    }
  }
  if (d.pairwise) text.push('pwcorr считает каждую пару по своим наблюдениям без пропусков, поэтому число наблюдений в парах может различаться (покажите его опцией obs). В регрессию попадут только наблюдения без пропусков во всех переменных.');
  return { verdict: 'info', title: 'Корреляционная матрица', text };
}

function graph(d: Extract<ResultData, { kind: 'graph' }>): Explanation {
  switch (d.graph) {
    case 'twoway':
    case 'scatter':
      return {
        verdict: 'info',
        title: 'Как читать график',
        text: [
          `Каждая точка — одно наблюдение: по горизонтали ${d.x}, по вертикали ${d.y}.`,
          d.slope !== undefined
            ? `Красная линия — прямая МНК. Она идёт ${d.slope > 0 ? 'вверх — связь прямая: чем больше ' + d.x + ', тем больше ' + d.y : 'вниз — связь обратная: чем больше ' + d.x + ', тем меньше ' + d.y}. Чем плотнее точки прижаты к линии, тем сильнее связь. Точки далеко от облака — возможные выбросы.`
            : 'Если облако вытянуто вверх-вправо — связь прямая, вниз-вправо — обратная, круглое — связи нет.',
        ],
        report: d.slope !== undefined ? `Диаграмма рассеяния показывает ${d.slope > 0 ? 'положительную' : 'отрицательную'} связь между ${d.x} и ${d.y}.` : undefined,
      };
    case 'kdensity':
      return {
        verdict: 'info',
        title: 'Как читать график плотности',
        text: [
          'Синяя линия — сглаженная гистограмма: где она выше, там больше наблюдений.',
          d.normal
            ? 'Красная линия — «идеальный» нормальный колокол с тем же средним и разбросом. Чем ближе синяя к красной, тем лучше выполняется нормальность (П5). Плохо: два горба, сильный перекос в одну сторону, длинный хвост.'
            : 'Добавьте опцию normal, чтобы сравнить с нормальным распределением: kdensity …, normal',
          'График — подсказка «на глаз»; формальный вывод о нормальности делайте по swilk.',
        ],
      };
    case 'acprplot':
      return {
        verdict: 'info',
        title: 'Как читать график',
        text: [
          `График проверяет, линейна ли связь ${d.x} с зависимой переменной с учётом остальных факторов (П1).`,
          d.lowess
            ? 'Красная прямая — линейная зависимость, синяя кривая (lowess) — как данные идут на самом деле. Синяя близка к красной — хорошо, связь линейная. Синяя заметно изгибается (дуга, S-образно) — связь нелинейная, попробуйте добавить квадрат фактора или логарифм.'
            : 'Добавьте опцию lowess, чтобы увидеть сглаженную кривую и сравнить её с прямой.',
        ],
      };
    case 'qnorm':
      return {
        verdict: 'info',
        title: 'Как читать квантильный график',
        text: [
          `Каждая точка — одно значение ${d.x}: по вертикали — фактическое, по горизонтали — каким оно было бы при нормальном распределении с тем же средним и разбросом.`,
          'Хорошо: точки лежат на прямой. Концы загибаются в разные стороны (слева вниз, справа вверх) — «тяжёлые хвосты», выбросы. Все точки идут дугой — асимметрия.',
          'График — подсказка «на глаз»; формальный вывод о нормальности (П5) делайте по swilk или sktest.',
        ],
      };
    case 'rvfplot':
      return {
        verdict: 'info',
        title: 'Как читать график остатков',
        text: [
          'По горизонтали — прогноз модели, по вертикали — ошибка (остаток). Линия на нуле — «нет ошибки».',
          'Хорошо: точки — ровная горизонтальная полоса вокруг нуля без закономерностей.',
          'Ищите «воронку»: если разброс точек растёт (или сужается) слева направо — это гетероскедастичность (П4 нарушена). Если точки образуют дугу — нелинейность (П1). Формальный вывод — по estat hettest.',
        ],
      };
  }
}
